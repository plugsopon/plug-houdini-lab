def S(s):
    return s % DIRS


def mk(parent, type_name, name, pos):
    n = parent.createNode(type_name, name)
    if parent is net:
        n.setPosition(hou.Vector2(pos[0], top + pos[1]))
    else:
        n.setPosition(hou.Vector2(pos[0], pos[1]))
    created.append(n)
    return n


def P(n, name, value):
    p = n.parm(name)
    if p is None:
        skipped.append((n.path(), name, "no such parm"))
        return
    try:
        p.deleteAllKeyframes()
        p.set(value)
    except Exception as e:
        skipped.append((n.path(), name, str(e)[:80]))


def E(n, name, expr, lang):
    p = n.parm(name)
    if p is None:
        skipped.append((n.path(), name, "no such parm"))
        return
    try:
        p.setExpression(expr, lang)
    except Exception as e:
        skipped.append((n.path(), name, str(e)[:80]))


def K(n, name, keys):
    p = n.parm(name)
    if p is None:
        skipped.append((n.path(), name, "no such parm"))
        return
    try:
        p.deleteAllKeyframes()
        for d in keys:
            k = hou.Keyframe()
            k.setFrame(d["f"])
            k.setValue(d["v"])
            if "x" in d:
                k.setExpression(d["x"], hou.exprLanguage.Hscript)
            if "si" in d:
                k.setInSlope(d["si"])
                k.setSlope(d["so"])
            if "ai" in d:
                k.setInAccel(d["ai"])
                k.setAccel(d["ao"])
            p.setKeyframe(k)
    except Exception as e:
        skipped.append((n.path(), name, str(e)[:80]))


def R(n, name, basis, keys, values):
    p = n.parm(name)
    if p is None:
        skipped.append((n.path(), name, "no such parm"))
        return
    try:
        b = [getattr(hou.rampBasis, x) for x in basis]
        p.set(hou.Ramp(b, keys, values))
    except Exception as e:
        skipped.append((n.path(), name, str(e)[:80]))


def W(dst, idx, src, oidx):
    dst.setInput(idx, src, oidx)


def SPARE(n, code):
    """Append a hand-made spare parm (template code read from the reference node)."""
    ns = {"hou": hou}
    exec(code, ns)
    ptg = n.parmTemplateGroup()
    ptg.append(ns["hou_parm_template"])
    n.setParmTemplateGroup(ptg)


def STASH_CURVES(n, prims):
    """The drawn petal outline: 3 open Bezier curves (order 4) stored in the Curve SOP's own stash."""
    g = hou.Geometry()
    for pts in prims:
        pr = g.createBezierCurve(len(pts), is_closed=False, order=4)
        for v, pos in zip(pr.vertices(), pts):
            v.point().setPosition(hou.Vector3(pos))
    n.parm("savedstashgeo").set(g)


def BOX(parent, comment, pos, size, color, members):
    b = parent.createNetworkBox()
    b.setComment(comment)
    b.setColor(hou.Color(color))
    for m in members:
        b.addNode(m)
    if parent is net:
        b.setPosition(hou.Vector2(pos[0], top + pos[1]))
    else:
        b.setPosition(hou.Vector2(pos[0], pos[1]))
    b.setSize(hou.Vector2(size[0], size[1]))
    return b


def STICKY(parent, text, pos, size, color, textcolor):
    s = parent.createStickyNote()
    s.setText(text)
    s.setColor(hou.Color(color))
    s.setTextColor(hou.Color(textcolor))
    s.setPosition(hou.Vector2(pos[0], pos[1]))
    s.setSize(hou.Vector2(size[0], size[1]))
    return s



