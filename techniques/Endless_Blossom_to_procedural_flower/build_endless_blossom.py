# ============================================================================
# Endless Blossom -> procedural flower   v001   (paste into Houdini Python Shell)
#
# Builds the whole Endless Blossom flower pipeline as 4 networks under /obj:
#   <PREFIX>_candidate   SOP   petal (feather tools) -> KineFX rig + 2 poses -> golden-angle
#                              blossom loop -> stem -> Vellum cloth emission -> endless loop
#   <PREFIX>_render_prep SOP   render shells, stem tube, backdrop, Entagma-recipe stem + fur
#   <PREFIX>_textures    SOP   Copernicus network that bakes 5 petal maps from the REST petal UVs
#   <PREFIX>_solaris     LOP   MaterialX petal material, camera, lights, Karma settings + ROP
# Reconstruction of the Entagma "Endless Blossom" tutorial (Christopher Kopic, 2025) done as a
# Houdini MCP benchmark (Dremzo Code, 2026-11-05). Every node / wire / value below was READ from
# the reviewed scene EB_full_v052bL3 by gen_builder.py; nothing was typed from memory.
#
# HOW TO USE
#   1. Open /obj (or any Object network) in the Network Editor.
#   2. Paste the whole file into Windows > Python Shell and press Enter.
#      -> 4 new networks, below whatever is already there. Nothing existing is changed.
#   3. The candidate's display flag lands on copy_blossom_to_stem_tip (blossom on the stem,
#      NO simulation). The endless loop (LOOP_OUT) reads a sim cache that you write with
#      eb_sim_cache.py (hython, bounded); the materials read maps written by eb_cook_textures.py.
#      Until those exist, LOOP_OUT and the Solaris petals are empty on purpose (missingframe = No Geometry).
#
#   INPUT_CURVES = "ai"    -> bundled AI-drawn petal outline / barb curve / stem curve (ours, redistributable)
#   INPUT_CURVES = "asset" -> the Entagma project curves from ASSET_DIR (3 .bgeo you export yourself
#                             with eb_extract_asset_curves.py from the project file you downloaded)
#   Existing nodes are never changed or moved. If /obj/<PREFIX>_candidate already exists the
#   script stops: pick another PREFIX, nothing is renamed or overwritten.
#
# Tested: Houdini 21.0.671 Apprentice (hython + verify_endless_blossom.py). Houdini 20.5 is NOT tested.
# ============================================================================

